test("high ports stay on 127.0.0.1, internal certificates never touch the keychain, and hostname mode has no wildcards", () => {
  const paths = proxyPaths("/r");
  const local = renderMainCaddyfile({
    settings: settings({
      ports: { http: 28080, https: 28443 },
      tls: { ca: "internal", certificates: "hostname" },
    }),
    paths,
    generation: "/r/caddy/generations/g2",
    hostnames: ["app.example.com"],
  });
  expect(local).toContain("\tdefault_bind 127.0.0.1\n");
  expect(local).toContain("\tlocal_certs\n\tskip_install_trust\n");
  expect(local).not.toContain("cert_issuer");
  expect(local).not.toContain("acme-dns.token");
  expect(local).not.toContain("abort");

  const staged = renderMainCaddyfile({
    settings: settings({ tls: { ca: "letsencrypt-staging" } }),
    paths,
    generation: "/r/caddy/generations/g3",
    hostnames: ["app.example.com", "x.share.example.com"],
  });
  expect(staged).toContain(
    'cert_issuer acme "https://acme-staging-v02.api.letsencrypt.org/directory" {',
  );
  expect(staged).not.toContain("default_bind");
  expect(staged).toContain(
    '"*.example.com" "*.share.example.com" {\n\tabort\n}',
  );

  expect(() =>
    renderMainCaddyfile({
      settings: settings(),
      paths: proxyPaths("/r with space"),
      generation: "/r with space/caddy/generations/g4",
      hostnames: [],
    }),
  ).toThrow(expect.objectContaining({ code: "PROXY_PATH" }));
});

test("a token is trimmed and must be one unbroken run of token characters; a malformed one is refused without echoing it", () => {
  const synthetic = "Syn_thetic-Token-0123456789abcdefABCDEF";
  expect(normalizeToken(`  ${synthetic}\n`)).toBe(synthetic);
  for (const bad of [
    "short",
    `${synthetic} trailing-word`,
    `"${synthetic}"`,
    `${synthetic}\n${synthetic}`,
    "",
  ]) {
    let error: unknown;
    try {
      normalizeToken(bad);
    } catch (caught) {
      error = caught;
    }
    expect(error).toMatchObject({ code: "PROXY_TOKEN" });
    expect(JSON.stringify(error)).not.toContain("Syn_thetic");
    expect(String((error as Error).message)).not.toContain("Syn_thetic");
  }
});

test("redaction removes the token's value and anything Caddy quotes after 'token', including a malformed paste", () => {
  const token = "Syn_thetic-Token-0123456789abcdefABCDEF";
  const caddy = `provision dns.providers.cloudflare: API token '${token}\n' appears invalid; ensure it's correctly entered`;
  const redacted = redactSecrets(caddy, [token]);
  expect(redacted).not.toContain("Syn_thetic");
  expect(redacted).toContain("[redacted]");
  // A value Rig does not know, quoted by the plugin, is still hidden.
  expect(
    redactSecrets("API token 'Other_synthetic_value_42' appears invalid", []),
  ).toBe("API token '[redacted]' appears invalid");
  // Output without a token is left alone.
  expect(redactSecrets("Valid configuration", [token])).toBe(
    "Valid configuration",
  );
});

test("Rig accepts exactly the token forms caddy-dns/cloudflare v0.2.4 accepts, so the plugin never quotes a token it rejects", () => {
  const classic = "A".repeat(35);
  expect(normalizeToken(classic)).toBe(classic);
  expect(normalizeToken("b".repeat(50))).toBe("b".repeat(50));
  expect(normalizeToken(`cfut_${"x".repeat(32)}`)).toBe(
    `cfut_${"x".repeat(32)}`,
  );
  expect(normalizeToken(`cfat_${"y_-".repeat(20)}`)).toBe(
    `cfat_${"y_-".repeat(20)}`,
  );
  for (const rejected of [
    "A".repeat(34),
    "A".repeat(51),
    `cfxx_${"x".repeat(60)}`,
    `cfut_${"x".repeat(40)}.`,
    `${"A".repeat(40)}=`,
  ])
    expect(() => normalizeToken(rejected)).toThrow(
      expect.objectContaining({ code: "PROXY_TOKEN" }),
    );
});

test("Caddy's JSON tells what Rig protects and the CAs it issues from", () => {
  const config = {
    admin: { listen: "unix//r/caddy/admin.sock|0600" },
    storage: { module: "file_system", root: "/r/caddy/data" },
    apps: {
      http: {
        http_port: 80,
        https_port: 443,
        servers: {
          srv0: {
            listen: [":443"],
            routes: [
              { match: [{ host: ["a.example.test", "*.example.test"] }] },
            ],
          },
          srv1: {
            listen: [":80"],
            routes: [{ match: [{ host: ["plain.example.test"] }] }],
          },
        },
      },
      tls: {
        automation: {
          policies: [
            {
              issuers: [
                {
                  module: "acme",
                  ca: "https://acme-v02.api.letsencrypt.org/directory",
                },
              ],
            },
          ],
        },
      },
    },
  };
  const expected = {
    admin: "unix//r/caddy/admin.sock|0600",
    storage: "/r/caddy/data",
    httpPort: 80,
    httpsPort: 443,
  };
  expect(protectedDifferences(config, expected)).toEqual([]);
  expect(
    protectedDifferences(
      {
        ...config,
        admin: { listen: "localhost:2999" },
        apps: {
          ...config.apps,
          http: { ...config.apps.http, https_port: 8443 },
        },
      },
      expected,
    ),
  ).toEqual(["admin", "https_port"]);
  // No site, no HTTP app: nothing listens, so the ports cannot differ.
  expect(
    protectedDifferences(
      { admin: config.admin, storage: config.storage },
      expected,
    ),
  ).toEqual([]);
  expect(issuerCas(config)).toEqual([
    "https://acme-v02.api.letsencrypt.org/directory",
  ]);
  expect(issuerCas({})).toEqual([]);
});

test("swapping which CA issues which subjects is a change, even though the set of CAs is the same", () => {
  const staging = "https://acme-staging-v02.api.letsencrypt.org/directory";
  const production = "https://acme-v02.api.letsencrypt.org/directory";
  const policies = (a: string, b: string) => ({
    apps: {
      tls: {
        automation: {
          policies: [
            {
              subjects: ["a.example.test"],
              issuers: [{ module: "acme", ca: a }],
            },
            {
              subjects: ["b.example.test"],
              issuers: [{ module: "acme", ca: b }],
            },
          ],
        },
      },
    },
  });
  expect(issuerCas(policies(staging, production))).toEqual(
    issuerCas(policies(production, staging)),
  );
  expect(issuancePolicies(policies(staging, production))).not.toBe(
    issuancePolicies(policies(production, staging)),
  );
  expect(issuancePolicies(policies(staging, production))).toBe(
    issuancePolicies(policies(staging, production)),
  );
});

test("a site address is one bare hostname to a client, whatever its scheme, port or case; proxy.routes is served sorted, a port meaning 127.0.0.1", () => {
  for (const address of [
    "app.example.test",
    "APP.example.test",
    "https://app.example.test:28443",
    "http://App.Example.Test:80",
  ])
    expect(bareHostname(address)).toBe("app.example.test");
  expect(
    hostRoutes(
      settings({
        routes: { "b.example.com": "localhost:9", "a.example.com": 3 },
      }),
    ),
  ).toEqual([
    { hostname: "a.example.com", upstream: "127.0.0.1:3" },
    { hostname: "b.example.com", upstream: "localhost:9" },
  ]);
});

test("every value written into a Caddyfile passes one gate: its field's shape, no Caddyfile syntax, then quoted", () => {
  expect(caddyValue("url", "https://acme.test/directory")).toBe(
    '"https://acme.test/directory"',
  );
  expect(caddyValue("port", 443)).toBe('"443"');
  for (const [field, value] of [
    ["url", "https://example.test/{$NAME}"],
    ["url", "https://example.test/{env.X}"],
    ["url", "https://example.test/x log"],
    ["url", 'https://example.test/"x'],
    ["url", "http://example.test/directory"],
    ["url", "https://example.test/x#y"],
    ["url", "https://example.test/x\\y"],
    ["email", "ops@example.com\n}"],
    ["hostname", "app.example.com {"],
    ["upstream", "10.0.0.5:80"],
    ["path", "/r with space"],
    ["port", 70000],
    ["module", "cloudflare\tx"],
    ["address", "app.test}"],
    ["prefix", "/a b"],
  ] as const)
    expect(() => checkCaddyValue(field, value)).toThrow(
      expect.objectContaining({
        code: field === "path" ? "PROXY_PATH" : "PROXY_CONFIG_INVALID",
      }),
    );
});

test("tls.ca is a named CA or a plain https URL: a placeholder that could expand into a directive is refused before anything renders", () => {
  // The round-5 reproduction: {$NAME} expands when Caddy parses the Caddyfile, so it could inject a global logger.
  for (const ca of [
    "https://example.test/{$NAME}",
    "https://example.test/directory\n\tlog",
    "https://example.test/{file./etc/passwd}",
    "https://example.test/dir ectory",
  ])
    expect(() => settings({ tls: { ca } })).toThrow();
  expect(() => settings({ tls: { email: "ops@example.com}" } })).toThrow();
  expect(settings({ tls: { ca: "https://acme.test/directory" } }).tls.ca).toBe(
    "https://acme.test/directory",
  );
  // Values that get past the schema some other way are still refused when rendered.
  const smuggled = settings();
  (smuggled.tls as { ca: string }).ca = "https://example.test/{$NAME}";
  expect(() =>
    renderMainCaddyfile({
      settings: smuggled,
      paths: proxyPaths("/r"),
      generation: "/r/caddy/generations/g9",
      hostnames: [],
    }),
  ).toThrow(expect.objectContaining({ code: "PROXY_CONFIG_INVALID" }));
});

test("a withheld one of proxy.routes (the dashboard's, until rigd confirms it holds its port) answers 503 and reaches no upstream", () => {
  const routes = { "grafana.example.com": 3000, "rig.example.com": 4280 };
  const text = renderMainCaddyfile({
    settings: settings({ routes }),
    paths: proxyPaths("/r"),
    generation: "/r/caddy/generations/g1",
    hostnames: [],
    withheld: ["rig.example.com"],
  });
  expect(text).toContain('"rig.example.com" {\n\trespond 503\n}');
  expect(text).not.toContain("127.0.0.1:4280");
  expect(text).toContain(
    '"grafana.example.com" {\n\treverse_proxy "127.0.0.1:3000"\n}',
  );
  expect(hostRoutes(settings({ routes }), ["rig.example.com"])).toEqual([
    { hostname: "grafana.example.com", upstream: "127.0.0.1:3000" },
    { hostname: "rig.example.com", upstream: null },
  ]);
});

test("Rig's own page answers for errors Caddy itself raises and for withheld paths, on every server", () => {
  const config = withDownPages({
    apps: {
      http: {
        servers: {
          srv0: {
            listen: [":443"],
            routes: [
              {
                handle: [
                  {
                    handler: "subroute",
                    routes: [
                      {
                        handle: [
                          { handler: "static_response", status_code: 503 },
                        ],
                      },
                      { handle: [{ handler: "static_response", abort: true }] },
                    ],
                  },
                ],
              },
            ],
          },
        },
      },
    },
  }) as {
    apps: {
      http: {
        servers: Record<
          string,
          {
            routes: { handle: { routes: { handle: unknown[] }[] }[] }[];
            errors: unknown;
          }
        >;
      };
    };
  };
  const server = config.apps.http.servers.srv0!;
  expect(server.routes[0]!.handle[0]!.routes[0]!.handle[0]).toEqual({
    handler: "static_response",
    status_code: 503,
    headers: { "Content-Type": ["text/plain; charset=utf-8"] },
    body: "503 - {http.request.host} is currently down",
  });
  // A connection Rig closes on purpose stays closed.
  expect(server.routes[0]!.handle[0]!.routes[1]!.handle[0]).toEqual({
    handler: "static_response",
    abort: true,
  });
  expect(server.errors).toEqual({
    routes: [
      {
        match: [{ expression: "{http.error.status_code} in [502, 503, 504]" }],
        handle: [
          {
            handler: "static_response",
            status_code: "{http.error.status_code}",
            headers: { "Content-Type": ["text/plain; charset=utf-8"] },
            body: "{http.error.status_code} - {http.request.host} is currently down",
          },
        ],
        terminal: true,
      },
    ],
  });
});
